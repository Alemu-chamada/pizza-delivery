const crypto = require('crypto');
const { getRazorpayInstance } = require('../config/razorpay');

/**
 * Payment Service
 * Handles Razorpay order creation and HMAC-SHA256 signature verification.
 * Plan Reference: project_plan.md §7.3, §11.2, §13, §15.2
 */

/**
 * Creates an order with Razorpay test gateway.
 * @param {number} amountPaise - Total amount in smallest currency unit (paise).
 * @param {string} currency - 3-letter currency code, default 'INR'.
 * @param {string} receipt - Optional internal order identifier or receipt.
 * @returns {Promise<Object>} Razorpay order object { id, amount, currency, status, ... }
 */
const createRazorpayOrder = async (amountPaise, currency = 'INR', receipt = '') => {
  const razorpay = getRazorpayInstance();
  const options = {
    amount: amountPaise,
    currency,
    receipt: receipt || `rcpt_${Date.now()}`,
  };

  const rzpOrder = await razorpay.orders.create(options);
  return rzpOrder;
};

/**
 * Verifies HMAC-SHA256 signature generated by Razorpay.
 * Formula: HMAC_SHA256(order_id + "|" + payment_id, secret)
 * @param {string} razorpayOrderId - The Razorpay order ID.
 * @param {string} razorpayPaymentId - The Razorpay payment ID.
 * @param {string} razorpaySignature - The signature sent by Razorpay client.
 * @returns {boolean} True if the signature matches, false otherwise.
 */
const verifySignature = (razorpayOrderId, razorpayPaymentId, razorpaySignature) => {
  if (!razorpayOrderId || !razorpayPaymentId || !razorpaySignature) {
    return false;
  }

  const keySecret = process.env.RAZORPAY_KEY_SECRET || 'placeholder_secret';
  const body = `${razorpayOrderId}|${razorpayPaymentId}`;

  const expectedSignature = crypto
    .createHmac('sha256', keySecret)
    .update(body)
    .digest('hex');

  const expectedBuffer = Buffer.from(expectedSignature, 'utf8');
  const signatureBuffer = Buffer.from(razorpaySignature, 'utf8');

  if (expectedBuffer.length !== signatureBuffer.length) {
    return false;
  }

  return crypto.timingSafeEqual(expectedBuffer, signatureBuffer);
};

module.exports = {
  createRazorpayOrder,
  verifySignature,
};
